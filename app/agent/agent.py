from datetime import datetime
from time import perf_counter

from app.agent.prompt import SYSTEM_PROMPT
from app.agent.session import Session
from app.config.logging_config import logger
from app.config.settings import CHAR_LIMIT_PER_MSG
from app.llm.gemini_client import GeminiClient


WEEKDAYS = [
    "segunda-feira",
    "terça-feira",
    "quarta-feira",
    "quinta-feira",
    "sexta-feira",
    "sábado",
    "domingo"
]


class Agent:
    """
    Orchestrates customer conversations using conversation history,
    the language model and available tools.
    """

    def __init__(self,gemini_client: GeminiClient,tools: list,session: Session):
        self.gemini_client = gemini_client
        self.tools = tools
        self.session = session


    @staticmethod
    def _system_instruction() -> str:
        """
        Build the system instruction with the current date and time.

        Returns:
            str: System instruction containing the current date and time.
        """

        now = datetime.now().astimezone()

        current_datetime = (f"{WEEKDAYS[now.weekday()]}, "f"{now:%d/%m/%Y}, {now:%H:%M}")

        return (f"{SYSTEM_PROMPT}\n\n"f"Data e hora atuais (Campo Grande/MS): {current_datetime}.")


    def handle_message(self, message: str) -> str:
        """
        Process a customer message and return the generated response.

        Args:
            message: Message sent by the customer.
        Returns
            str: Response generated by the language model.
        """

        if len(message) > CHAR_LIMIT_PER_MSG:
            return ("Sua mensagem ficou muito longa para eu processar 😅 "
            "Pode resumir em poucas linhas, por favor?")

        # Save the message only after a successful response.
        history = self.session.get_history()
        history.append({"role": "user","content": message})

        contents = [{
                "role": "user" if history_item["role"] == "user" else "model",
                "parts": [{"text": history_item["content"]}]
            }for history_item in history
        ]

        start_time = perf_counter()

        response = self.gemini_client.generate_response(
            contents=contents,
            system_instruction=self._system_instruction(),
            tools=self.tools
        )

        execution_time = perf_counter() - start_time
        logger.info("[PERFORMANCE] LLM + tools: %.2fs", execution_time)

        self.session.add_message("user", message)
        self.session.add_message("assistant", response)

        return response
    
